def path(n):
    return C / f'2026-10-08-малайзия-{n}.json'


def load(n):
    return json.loads(path(n).read_text(encoding='utf-8'))


def save(n, d):
    path(n).write_text(json.dumps(d, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def slide(d, typ):
    return next(s for s in d['slides'] if s['type'] == typ)


def comp(d, key):
    k = key.lower()
    for s in d['slides']:
        if s['type'] == 'company' and (s['title'].lower().startswith(k) or s.get('short', '').lower().startswith(k)):
            return s
    raise KeyError(key)


def F(icon, value, label, sub=None):
    f = {'icon': icon, 'value': value, 'label': label}
    if sub:
        f['sub'] = sub
    return f


def card(d, key, facts=None, **kw):
    s = comp(d, key)
    if facts is not None:
        assert len(facts) == 4, key
        s['facts'] = facts
    for k, v in kw.items():
        if v is None:
            s.pop(k, None)
        else:
            s[k] = v
    return s


def day(d, n, **kw):
    dd = slide(d, 'days')['days'][n - 1]
    dd.update(kw)


def layer(d, i, text):
    slide(d, 'layers')['items'][i]['text'] = text


def city(d, i, **kw):
    slide(d, 'route')['cities'][i].update(kw)


