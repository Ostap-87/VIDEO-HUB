def path(n):
    return C / f'2026-10-08-корея-{n}.json'


def load(n):
    return json.loads(path(n).read_text(encoding='utf-8'))


def save(n, d):
    path(n).write_text(json.dumps(d, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def slide(d, typ):
    return next(s for s in d['slides'] if s['type'] == typ)


def comp(d, key):
    k = key.lower()
    for s in d['slides']:
        if s['type'] == 'company' and (s['title'].lower().startswith(k) or s.get('short', '').lower().startswith(k)):
            return s
    raise KeyError(key)


def F(icon, value, label, sub=None):
    f = {'icon': icon, 'value': value, 'label': label}
    if sub:
        f['sub'] = sub
    return f


def card(d, key, facts=None, **kw):
    s = comp(d, key)
    if facts is not None:
        assert len(facts) == 4, key
        s['facts'] = facts
    for k, v in kw.items():
        if v is None:
            s.pop(k, None)
        else:
            s[k] = v
    return s


def day(d, n, **kw):
    slide(d, 'days')['days'][n - 1].update(kw)


def layer(d, i, text, name=None):
    it = slide(d, 'layers')['items'][i]
    it['text'] = text
    if name:
        it['name'] = name


def why(d, hq, route, support):
    items = slide(d, 'why')['items']
    items[1]['text'], items[2]['text'], items[3]['text'] = hq, route, support


def benefits(d, items):
    """items: [(индекс, заголовок, текст, иконка)] — заголовок/иконка None = не трогать."""
    b = slide(d, 'benefits')['items']
    for i, title, text, icon in items:
        if title:
            b[i]['title'] = title
        b[i]['text'] = text
        if icon:
            b[i]['icon'] = icon


def city(name, days, companies, leg=None):
    c = {'name': name, 'days': days, 'companies': companies}
    if leg:
        c['leg'] = {'icon': leg[0], 'text': leg[1]}
    return c


