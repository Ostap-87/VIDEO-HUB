export const emojiSrc = (file: string) => `интернет-материалы/эмодзи/${file}.webp`;
export const emojiByFile = (file: string) => EMOJI.find((e) => e.file === file);

// эмодзи по тексту: сначала сами символы (🔥), потом слова
export function findEmoji(text: string): Emoji | undefined {
  const plain = (s: string) => s.replace(/️/g, "");
  for (const e of EMOJI) if (plain(text).includes(plain(e.char))) return e;
  const low = text.toLowerCase().replace(/ё/g, "е");
  let best: {e: Emoji; len: number} | undefined;
  for (const e of EMOJI)
    for (const w of e.words) {
      const ww = w.replace(/ё/g, "е");
      if (new RegExp(`(^|[^а-яa-z0-9])${ww.replace(/[-]/g, "[- ]?")}([^а-яa-z0-9]|$)`).test(low) && (!best || ww.length > best.len)) best = {e, len: ww.length};
    }
  return best?.e;
}
